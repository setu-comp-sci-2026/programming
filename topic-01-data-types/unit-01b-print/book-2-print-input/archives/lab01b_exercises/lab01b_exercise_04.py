num1 = float(input("Enter first number: "))
num2 = float(input("Enter second number: "))

sum = num1 + num2   
difference = num1 - num2
product = num1 * num2
quotient = num1 / num2

print(f"Sum:        {sum:.2f}")
print(f"Difference: {difference:.2f}")
print(f"Product:    {product:.2f}")
print(f"Quotient:   {quotient:.2f}")


